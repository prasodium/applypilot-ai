DOCX_MIME = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
ALLOWED = {".pdf": {"application/pdf"}, ".docx": {DOCX_MIME}}
MAX_PDF_PAGES = 30
MAX_DOCX_UNCOMPRESSED = 50 * 1024 * 1024
MAX_DOCX_ENTRIES = 2000
DEMO_BANNER = "[DEMO DRAFT: generated by the mock AI provider. Review and edit before using it anywhere.]"


# ------------------------------------------------------------------ upload validation + extraction
def safe_display_name(name: str) -> str:
    base = os.path.basename((name or "").replace("\\", "/"))
    base = re.sub(r"[\x00-\x1f\x7f<>:\"|?*]", "", base).strip(". ")
    return base[:200] or "resume"


def _extract_pdf(data: bytes) -> str:
    doc = pymupdf.open(stream=data, filetype="pdf")
    try:
        if doc.needs_pass or doc.is_encrypted:
            raise Unprocessable("The PDF is password-protected. Remove the password and upload it again.", code="encrypted_pdf")
        if doc.page_count > MAX_PDF_PAGES:
            raise Unprocessable(f"The PDF has more than {MAX_PDF_PAGES} pages; a résumé should be shorter.", code="too_many_pages")
        return "\n".join(doc.load_page(i).get_text() for i in range(doc.page_count))
    finally:
        doc.close()


def _extract_docx(data: bytes) -> str:
    d = DocxDocument(io.BytesIO(data))
    parts = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            parts.append("  ".join(c.text.strip() for c in row.cells))
    return "\n".join(parts)


def _check_docx_structure(data: bytes) -> None:
    if not zipfile.is_zipfile(io.BytesIO(data)):
        raise Unprocessable("This is not a valid .docx file.", code="invalid_file")
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        infos = z.infolist()
        if len(infos) > MAX_DOCX_ENTRIES or sum(i.file_size for i in infos) > MAX_DOCX_UNCOMPRESSED:
            raise Unprocessable("The document is unusually large when unpacked and was rejected.", code="zip_bomb_suspected")
        if "word/document.xml" not in {i.filename for i in infos}:
            raise Unprocessable("This is not a valid .docx file.", code="invalid_file")


def upload_resume(db: Session, *, filename: str, content_type: str | None, data: bytes, upload_dir: Path,
                  max_bytes: int) -> CandidateDocument:
    """Validates extension, declared MIME type, size, magic bytes and parseability; stores nothing unless all pass."""
    display = safe_display_name(filename)
    ext = Path(display).suffix.lower()
    if ext not in ALLOWED:
        raise Unprocessable("Only .pdf and .docx files are accepted.", code="unsupported_type")
    if not data:
        raise Unprocessable("The file is empty.", code="empty_file")
    if len(data) > max_bytes:
        raise PayloadTooLarge(f"The file is larger than the {max_bytes // (1024 * 1024)} MB limit.", code="file_too_large")
    ctype = (content_type or "").split(";")[0].strip().lower()
    if ctype and ctype != "application/octet-stream" and ctype not in ALLOWED[ext]:
        raise Unprocessable("The file's declared type does not match its extension.", code="mime_mismatch")
    if ext == ".pdf" and not data.startswith(b"%PDF-"):
        raise Unprocessable("This is not a valid PDF file.", code="invalid_file")
    if ext == ".docx":
        _check_docx_structure(data)
    try:
        text = _extract_pdf(data) if ext == ".pdf" else _extract_docx(data)
    except Unprocessable:
        raise
    except Exception as exc:  # corrupt/malicious structure: report generically, never echo parser internals
        log.warning("document extraction failed: %s", type(exc).__name__)
        raise Unprocessable("The file could not be read. It may be corrupted.", code="unreadable_file") from exc
    text = sanitize_external_text(text, max_len=200_000)
    if len(text) < 40:
        raise Unprocessable("No readable text was found (scanned images are not supported).", code="no_text")

    rel = Path("resumes") / f"{uuid.uuid4().hex}{ext}"  # server-chosen name: no user-controlled path component
    full = upload_dir / rel
    full.parent.mkdir(parents=True, exist_ok=True)
    os.chmod(full.parent, 0o700)
    fd = os.open(full, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as fh:
        fh.write(data)
    import hashlib

    doc = CandidateDocument(kind=DocumentKind.RESUME_UPLOAD.value, filename=display, mime_type=next(iter(ALLOWED[ext])),
                            size_bytes=len(data), sha256=hashlib.sha256(data).hexdigest(), storage_path=str(rel),
                            text_content=text, status="draft")
    db.add(doc)
    db.flush()
    parse_document(db, doc.id)
    audit.record(db, "document_uploaded", f"Résumé uploaded ({ext}, {len(data)} bytes)", entity_type="document", entity_id=doc.id)
    return doc


def get_document(db: Session, doc_id: int) -> CandidateDocument:
    d = db.get(CandidateDocument, doc_id)
    if d is None:
        raise NotFound(f"Document {doc_id} not found")
    return d


def parse_document(db: Session, doc_id: int) -> CandidateDocument:
    d = get_document(db, doc_id)
    if d.kind != DocumentKind.RESUME_UPLOAD.value:
        raise Unprocessable("Only uploaded résumés can be parsed.", code="not_parseable")
    parsed = parse_resume_text(d.text_content)
    d.parsed_data = parsed.model_dump(mode="json")
    d.parse_status, d.parse_error = "parsed", ""
    return d


def apply_parse(db: Session, doc_id: int, body: ApplyParseIn) -> None:
    """Writes the user-reviewed preview into the profile. confirm=True means the user has checked it -> user_confirmed."""
    d = get_document(db, doc_id)
    if d.kind != DocumentKind.RESUME_UPLOAD.value:
        raise Unprocessable("Only uploaded résumés can be applied.", code="not_parseable")
    src = FactSource.USER_CONFIRMED if body.confirm else FactSource.RESUME_EXTRACTED_UNCONFIRMED
    p = profile_svc.get_profile(db)
    if body.replace_existing:
        for coll in (p.education, p.experience, p.skills, p.projects):
            for r in list(coll):
                db.delete(r)
        db.flush()
        db.refresh(p)
    if body.apply_profile_fields:
        incoming = body.parsed.profile.model_dump()
        for k, v in incoming.items():
            if k != "preferred_contact" and v not in ("", None) and k in ProfileFields.model_fields and getattr(p, k) in ("", None):
                setattr(p, k, v)  # only fills gaps; never overwrites what the user already entered
    existing_edu = {(e.institution.lower(), e.degree.lower()) for e in p.education}
    existing_exp = {(x.employer.lower(), x.title.lower(), x.start_date) for x in p.experience}
    existing_skills = {s.name_key for s in db.scalars(select(Skill).where(Skill.profile_id == p.id))}
    counts = {"education": 0, "experience": 0, "skills": 0, "projects": 0}
    for e in body.parsed.education:
        if (e.institution.lower(), e.degree.lower()) not in existing_edu:
            profile_svc.add_education(db, e, source=src, confirmed=body.confirm)
            counts["education"] += 1
    for x in body.parsed.experience:
        if (x.employer.lower(), x.title.lower(), x.start_date) not in existing_exp:
            profile_svc.add_experience(db, x, source=src, confirmed=body.confirm)
            counts["experience"] += 1
    for s in body.parsed.skills:
        if s.name.strip().lower() not in existing_skills:
            profile_svc.add_skill(db, s, source=src, confirmed=body.confirm)
            existing_skills.add(s.name.strip().lower())
            counts["skills"] += 1
    existing_proj = {j.name.lower() for j in p.projects}
    for j in body.parsed.projects:
        if j.name.lower() not in existing_proj:
            profile_svc.add_project(db, j, source=src, confirmed=body.confirm)
            counts["projects"] += 1
    db.expire(p, profile_svc._REL)
    d.parse_status = "applied"
    d.parsed_data = body.parsed.model_dump(mode="json")
    audit.record(db, "resume_applied", "Résumé data saved to the profile", entity_type="document", entity_id=d.id,
                 meta={"confirmed": body.confirm, **counts})
    db.flush()
    if body.confirm:
        generate_master_resume(db)


# ------------------------------------------------------------------ résumé content (grounded in confirmed facts)
def _dates(a: str, b: str, current: bool = False) -> str:
    if not a and not b:
        return ""
    return f"{a or '?'} - {'Present' if current and not b else (b or '?')}"


def build_resume_content(db: Session, job: JobListing | None) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Selects and orders CONFIRMED facts only. Never rewrites wording; every line carries the id of its source fact."""
    p = profile_svc.fresh_profile(db)
    claims: list[dict[str, Any]] = []
    want: set[str] = set()
    if job:
        want = {s.lower() for s in find_skills(" ".join([job.title, job.description, *job.required_qualifications, *job.preferred_qualifications]))}

    def rel(text: str) -> int:
        return len({s.lower() for s in find_skills(text)} & want)

    def claim(text: str, fid: str) -> None:
        claims.append({"text": text, "source_fact_ids": [fid]})

    content: dict[str, Any] = {
        "name": p.legal_name, "headline": p.headline,
        "contact": [x for x in (p.email, p.phone, ", ".join(v for v in (p.city, p.country) if v), p.linkedin_url, p.github_url,
                                p.portfolio_url) if x],
        "summary": p.summary, "skills": [], "experience": [], "projects": [], "education": [],
    }
    if p.summary:
        claim(p.summary, "personal:summary")
    skills = [s for s in p.skills if s.confirmed]
    skills.sort(key=lambda s: (0 if s.name.lower() in want else 1, s.id))  # relevant skills first; nothing added or removed
    for s in skills:
        content["skills"].append({"name": s.name, "fact_id": f"skill:{s.id}"})
        claim(s.name, f"skill:{s.id}")
    exps = [x for x in p.experience if x.confirmed]
    for x in exps:  # keep chronological order; reorder bullets so relevant ones come first, wording untouched
        bullets = [*x.achievements, *x.responsibilities]
        bullets.sort(key=lambda b: -rel(b))
        fid = f"exp:{x.id}"
        content["experience"].append({"title": x.title, "employer": x.employer, "dates": _dates(x.start_date, x.end_date, x.is_current),
                                      "location": x.location, "bullets": bullets, "technologies": x.technologies, "fact_id": fid})
        claim(f"{x.title}, {x.employer}", fid)
        for b in bullets:
            claim(b, fid)
    projs = [j for j in p.projects if j.confirmed]
    projs.sort(key=lambda j: -rel(" ".join([j.name, j.summary, *j.technologies, *j.related_skills])))
    for j in projs[: 3 if job else 6]:
        fid = f"proj:{j.id}"
        content["projects"].append({"name": j.name, "summary": j.summary, "technologies": j.technologies, "url": j.url,
                                    "results": j.results, "fact_id": fid})
        claim(f"{j.name}: {j.summary}", fid)
    for e in (e for e in p.education if e.confirmed):
        fid = f"edu:{e.id}"
        line = " - ".join(x for x in (f"{e.degree} {('in ' + e.major) if e.major else ''}".strip(), e.institution) if x)
        content["education"].append({"line": line, "dates": _dates(e.start_date, e.end_date), "gpa": e.gpa, "gpa_scale": e.gpa_scale,
                                     "expected": e.is_expected, "fact_id": fid})
        claim(line, fid)
    return content, claims


def render_resume_text(c: dict[str, Any]) -> str:
    out = [c["name"] or "(name not set)"]
    if c.get("headline"):
        out.append(c["headline"])
    if c.get("contact"):
        out.append(" | ".join(c["contact"]))
    if c.get("summary"):
        out += ["", "SUMMARY", c["summary"]]
    if c.get("skills"):
        out += ["", "SKILLS", ", ".join(s["name"] for s in c["skills"])]
    if c.get("experience"):
        out += ["", "EXPERIENCE"]
        for x in c["experience"]:
            out.append(f"{x['title']}, {x['employer']}" + (f" ({x['dates']})" if x["dates"] else ""))
            out += [f"- {b}" for b in x["bullets"]]
    if c.get("projects"):
        out += ["", "PROJECTS"]
        for j in c["projects"]:
            out.append(j["name"] + (f" - {j['url']}" if j["url"] else ""))
            if j["summary"]:
                out.append(f"- {j['summary']}")
            if j["technologies"]:
                out.append("- Technologies: " + ", ".join(j["technologies"]))
    if c.get("education"):
        out += ["", "EDUCATION"]
        for e in c["education"]:
            out.append(e["line"] + (f" ({e['dates']})" if e["dates"] else "") + (f", GPA {e['gpa']}" + (f"/{e['gpa_scale']}" if e["gpa_scale"] else "") if e["gpa"] else ""))
    return "\n".join(out).strip() + "\n"


def _next_version(db: Session, kind: str, job_id: int | None) -> tuple[int, int | None]:
    q = select(CandidateDocument).where(CandidateDocument.kind == kind)
    q = q.where(CandidateDocument.job_id == job_id) if job_id is not None else q.where(CandidateDocument.job_id.is_(None))
    last = db.scalar(q.order_by(CandidateDocument.version.desc()).limit(1))
    return (last.version + 1, last.id) if last else (1, None)


def generate_master_resume(db: Session) -> CandidateDocument:
    content, claims = build_resume_content(db, None)
    v, parent = _next_version(db, DocumentKind.MASTER_RESUME.value, None)
    doc = CandidateDocument(kind=DocumentKind.MASTER_RESUME.value, filename="master-resume.txt", mime_type="text/plain",
                            text_content=render_resume_text(content), parsed_data=content, claims=claims, version=v,
                            parent_id=parent, status="draft", parse_status="parsed")
    db.add(doc)
    db.flush()
    audit.record(db, "master_resume_generated", f"Master résumé v{v} generated from confirmed facts", entity_type="document", entity_id=doc.id)
    return doc


def generate_tailored_resume(db: Session, job_id: int, notes: str = "") -> CandidateDocument:
    job = db.get(JobListing, job_id)
    if job is None:
        raise NotFound(f"Job {job_id} not found")
    content, claims = build_resume_content(db, job)
    if not content["experience"] and not content["projects"] and not content["skills"] and not content["education"]:
        raise Unprocessable("There are no confirmed profile facts to build a résumé from. Confirm your profile first.", code="no_confirmed_facts")
    v, parent = _next_version(db, DocumentKind.TAILORED_RESUME.value, job_id)
    doc = CandidateDocument(kind=DocumentKind.TAILORED_RESUME.value, filename=f"resume-{job.company}-{job.title}.txt"[:200],
                            mime_type="text/plain", text_content=render_resume_text(content), parsed_data=content, claims=claims,
                            version=v, parent_id=parent, job_id=job_id, status="draft", parse_status="parsed")
    db.add(doc)
    db.flush()
    audit.record(db, "resume_draft_generated", f"Tailored résumé draft v{v} generated", entity_type="document", entity_id=doc.id,
                 meta={"job_id": job_id})
    return doc


def generate_cover_letter(db: Session, ai: LLMProvider, job_id: int, notes: str = "") -> CandidateDocument:
    job = db.get(JobListing, job_id)
    if job is None:
        raise NotFound(f"Job {job_id} not found")
    p = profile_svc.get_profile(db)
    facts = profile_svc.confirmed_facts(db)
    if not any(f.kind in {"experience", "project", "skill", "education"} for f in facts):
        raise Unprocessable("There are no confirmed profile facts to write a cover letter from.", code="no_confirmed_facts")
    payload = {
        "candidate": {"name": p.legal_name},
        "job": {"title": job.title, "company": job.company},
        "required_skills": find_skills(" ".join([*job.required_qualifications, job.title])),
        "facts": [{"id": f.id, "kind": f.kind, "label": f.label, "text": f.text, "fields": _fact_fields(db, f.id)} for f in facts],
        "untrusted": {"job_description": job.description[:4000]},
    }
    try:
        out = ai.generate("cover_letter", payload, CoverLetterOut)
    except ProviderError as exc:
        raise Unprocessable("The AI provider could not produce a cover letter. Try again or write it manually.", code="ai_unavailable") from exc

    allowed_ids = {f.id for f in facts}
    by_id = {f.id: f.text for f in facts}
    claims: list[dict[str, Any]] = []
    for para in out.paragraphs:
        bad = invalid_fact_ids(para.source_fact_ids, allowed_ids)
        if bad:
            raise Unprocessable("The generated letter cited facts that are not confirmed; it was discarded.", code="ungrounded_output")
        nums = unsupported_numbers(para.text, [by_id[i] for i in para.source_fact_ids], [job.title, job.company, p.legal_name])
        if nums:
            raise Unprocessable("The generated letter contained numbers that are not in your confirmed facts; it was discarded.",
                                code="ungrounded_output", details={"numbers": sorted(nums)})
        claims.append({"text": para.text, "source_fact_ids": para.source_fact_ids})
    body = "\n\n".join(c["text"] for c in claims)
    if ai.is_demo:
        body = f"{DEMO_BANNER}\n\n{body}"
    v, parent = _next_version(db, DocumentKind.COVER_LETTER.value, job_id)
    doc = CandidateDocument(kind=DocumentKind.COVER_LETTER.value, filename=f"cover-letter-{job.company}.txt"[:200], mime_type="text/plain",
                            text_content=body, parsed_data={"paragraphs": claims}, claims=claims, version=v, parent_id=parent,
                            job_id=job_id, status="draft", parse_status="parsed", is_demo=ai.is_demo)
    db.add(doc)
    db.flush()
    audit.record(db, "cover_letter_generated", f"Cover letter draft v{v} generated", entity_type="document", entity_id=doc.id,
                 meta={"job_id": job_id, "demo": ai.is_demo})
    return doc


def _fact_fields(db: Session, fact_id: str) -> dict[str, Any]:
    """Structured fields of a confirmed fact (so a provider can quote it accurately instead of paraphrasing)."""
    kind, _, ident = fact_id.partition(":")
    if not ident.isdigit():
        return {}
    if kind == "exp":
        x = db.get(WorkExperience, int(ident))
        return {"employer": x.employer, "title": x.title, "responsibilities": x.responsibilities, "achievements": x.achievements,
                "technologies": x.technologies} if x else {}
    if kind == "proj":
        from app.models import CandidateProject

        j = db.get(CandidateProject, int(ident))
        return {"name": j.name, "summary": j.summary, "contribution": j.contribution, "results": j.results,
                "technologies": j.technologies} if j else {}
    if kind == "edu":
        e = db.get(EducationRecord, int(ident))
        return {"institution": e.institution, "degree": e.degree, "major": e.major} if e else {}
    return {}


# ------------------------------------------------------------------ edit / approve / diff / render
def edit_text(db: Session, doc_id: int, text: str) -> CandidateDocument:
    d = get_document(db, doc_id)
    if d.kind == DocumentKind.RESUME_UPLOAD.value:
        raise Unprocessable("Uploaded originals cannot be edited. Edit a generated draft instead.", code="not_editable")
    d.text_content = sanitize_external_text(text, max_len=100_000)
    d.status = "draft"  # any edit revokes a previous approval
    d.claims = [{"text": d.text_content, "source_fact_ids": [], "user_edited": True}]
    audit.record(db, "document_edited", "Draft edited by the user", entity_type="document", entity_id=d.id)
    return d


def approve(db: Session, doc_id: int) -> CandidateDocument:
    d = get_document(db, doc_id)
    if d.kind == DocumentKind.RESUME_UPLOAD.value:
        raise Unprocessable("Only generated drafts can be approved.", code="not_approvable")
    d.status = "approved"
    audit.record(db, "document_approved", "Draft approved by the user", entity_type="document", entity_id=d.id)
    return d


def delete_document(db: Session, doc_id: int, upload_dir: Path) -> None:
    d = get_document(db, doc_id)
    if d.storage_path:
        (upload_dir / d.storage_path).unlink(missing_ok=True)
    db.delete(d)
    audit.record(db, "document_deleted", "Document deleted", entity_type="document", entity_id=doc_id)


def diff(db: Session, doc_id: int, against_id: int) -> list[str]:
    a, b = get_document(db, against_id), get_document(db, doc_id)
    return list(difflib.unified_diff(a.text_content.splitlines(), b.text_content.splitlines(),
                                     fromfile=f"v{a.version} (#{a.id})", tofile=f"v{b.version} (#{b.id})", lineterm=""))


def render_docx(d: CandidateDocument) -> bytes:
    doc = DocxDocument()
    for i, line in enumerate(d.text_content.splitlines()):
        if re.fullmatch(r"[A-Z ]{4,}", line.strip()) and line.strip():
            doc.add_heading(line.strip().title(), level=2)
        elif line.startswith("- "):
            doc.add_paragraph(line[2:], style="List Bullet")
        elif i == 0 and d.kind != DocumentKind.COVER_LETTER.value:
            doc.add_heading(line, level=1)
        else:
            doc.add_paragraph(line)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def render_pdf(d: CandidateDocument) -> bytes:
    body = "".join(f"<p>{html.escape(line) or '&nbsp;'}</p>" for line in d.text_content.splitlines())
    story = pymupdf.Story(html=f"<body>{body}</body>", user_css="body{font-family:sans-serif;font-size:10pt} p{margin:0 0 3pt 0}")
    buf = io.BytesIO()
    writer = pymupdf.DocumentWriter(buf)
    media = pymupdf.paper_rect("letter")
    where = media + (50, 50, -50, -50)
    more = 1
    while more:
        dev = writer.begin_page(media)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()
    return buf.getvalue()


def count_versions(db: Session, kind: str, job_id: int | None) -> int:
    q = select(func.count()).select_from(CandidateDocument).where(CandidateDocument.kind == kind)
    q = q.where(CandidateDocument.job_id == job_id) if job_id is not None else q
    return db.scalar(q) or 0


