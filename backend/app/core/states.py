"""Central workflow state machine. The orchestrator (never the AI) is the only thing allowed to change state."""
from __future__ import annotations

from app.core.enums import AppState as S

# Allowed transitions. Anything not listed is rejected.
TRANSITIONS: dict[S, set[S]] = {
    S.JOB_DISCOVERED: {S.JOB_ANALYZED, S.JOB_CLOSED, S.APPLICATION_PREPARING},
    S.JOB_ANALYZED: {S.JOB_SHORTLISTED, S.JOB_CLOSED, S.APPLICATION_PREPARING},
    S.JOB_SHORTLISTED: {S.APPLICATION_PREPARING, S.JOB_CLOSED},
    S.APPLICATION_PREPARING: {
        S.PROFILE_INFORMATION_REQUIRED, S.FORM_IN_PROGRESS, S.READY_FOR_REVIEW, S.LOGIN_REQUIRED,
        S.ACCOUNT_CREATION_REQUIRED, S.EMAIL_VERIFICATION_REQUIRED, S.HUMAN_VERIFICATION_REQUIRED,
        S.APPLICATION_FAILED, S.APPLICATION_WITHDRAWN, S.JOB_CLOSED,
    },
    S.LOGIN_REQUIRED: {S.FORM_IN_PROGRESS, S.APPLICATION_PREPARING, S.APPLICATION_WITHDRAWN, S.APPLICATION_FAILED},
    S.ACCOUNT_CREATION_REQUIRED: {S.FORM_IN_PROGRESS, S.APPLICATION_PREPARING, S.APPLICATION_WITHDRAWN, S.APPLICATION_FAILED},
    S.EMAIL_VERIFICATION_REQUIRED: {S.FORM_IN_PROGRESS, S.APPLICATION_PREPARING, S.APPLICATION_WITHDRAWN, S.APPLICATION_FAILED},
    S.HUMAN_VERIFICATION_REQUIRED: {S.FORM_IN_PROGRESS, S.APPLICATION_PREPARING, S.SUBMISSION_IN_PROGRESS,
                                    S.APPLICATION_WITHDRAWN, S.APPLICATION_FAILED},
    S.PROFILE_INFORMATION_REQUIRED: {S.FORM_IN_PROGRESS, S.APPLICATION_PREPARING, S.READY_FOR_REVIEW,
                                     S.APPLICATION_WITHDRAWN, S.APPLICATION_FAILED},
    S.FORM_IN_PROGRESS: {
        S.PROFILE_INFORMATION_REQUIRED, S.FORM_VALIDATION_FAILED, S.READY_FOR_REVIEW, S.LOGIN_REQUIRED,
        S.HUMAN_VERIFICATION_REQUIRED, S.EMAIL_VERIFICATION_REQUIRED, S.APPLICATION_FAILED,
        S.APPLICATION_WITHDRAWN, S.JOB_CLOSED, S.APPLICATION_PREPARING,
    },
    S.FORM_VALIDATION_FAILED: {S.FORM_IN_PROGRESS, S.PROFILE_INFORMATION_REQUIRED, S.APPLICATION_WITHDRAWN, S.APPLICATION_FAILED},
    S.READY_FOR_REVIEW: {
        S.SUBMISSION_PENDING_APPROVAL, S.FORM_IN_PROGRESS, S.PROFILE_INFORMATION_REQUIRED,
        S.APPLICATION_WITHDRAWN, S.APPLICATION_PREPARING, S.JOB_CLOSED,
        S.SUBMITTED,  # only via a user-attested manual application (see services.applications.attest_manual)
    },
    S.SUBMISSION_PENDING_APPROVAL: {
        S.SUBMISSION_IN_PROGRESS, S.READY_FOR_REVIEW,  # approval revoked/invalidated -> back to review
        S.PROFILE_INFORMATION_REQUIRED, S.APPLICATION_WITHDRAWN,
    },
    S.SUBMISSION_IN_PROGRESS: {
        S.SUBMITTED, S.SUBMISSION_UNCONFIRMED, S.FORM_VALIDATION_FAILED, S.HUMAN_VERIFICATION_REQUIRED,
        S.LOGIN_REQUIRED, S.APPLICATION_FAILED,
        # Before the submit control is clicked nothing has been sent, so these are safe exits:
        S.PROFILE_INFORMATION_REQUIRED, S.SUBMISSION_PENDING_APPROVAL, S.READY_FOR_REVIEW,
        S.EMAIL_VERIFICATION_REQUIRED, S.ACCOUNT_CREATION_REQUIRED,
    },
    S.SUBMITTED: {S.APPLICATION_WITHDRAWN},
    # No automatic path out of UNCONFIRMED: only a user-attested resolution (SUBMITTED / FAILED) or withdrawal.
    S.SUBMISSION_UNCONFIRMED: {S.SUBMITTED, S.APPLICATION_FAILED, S.APPLICATION_WITHDRAWN},
    S.APPLICATION_FAILED: {S.APPLICATION_PREPARING, S.APPLICATION_WITHDRAWN},
    S.APPLICATION_WITHDRAWN: set(),
    S.JOB_CLOSED: set(),
}

TERMINAL = {S.SUBMITTED, S.APPLICATION_WITHDRAWN, S.JOB_CLOSED, S.SUBMISSION_UNCONFIRMED}
# States in which the form data can still be edited by the user.
EDITABLE = {
    S.APPLICATION_PREPARING, S.PROFILE_INFORMATION_REQUIRED, S.FORM_IN_PROGRESS, S.FORM_VALIDATION_FAILED,
    S.READY_FOR_REVIEW, S.SUBMISSION_PENDING_APPROVAL, S.LOGIN_REQUIRED, S.HUMAN_VERIFICATION_REQUIRED,
    S.EMAIL_VERIFICATION_REQUIRED, S.ACCOUNT_CREATION_REQUIRED, S.APPLICATION_FAILED,
}
# States that need the human to do something before the workflow can continue.
NEEDS_USER = {
    S.LOGIN_REQUIRED, S.ACCOUNT_CREATION_REQUIRED, S.EMAIL_VERIFICATION_REQUIRED, S.HUMAN_VERIFICATION_REQUIRED,
    S.PROFILE_INFORMATION_REQUIRED, S.READY_FOR_REVIEW, S.SUBMISSION_PENDING_APPROVAL, S.SUBMISSION_UNCONFIRMED,
    S.FORM_VALIDATION_FAILED,
}


class InvalidTransition(Exception):
    def __init__(self, src: S, dst: S):
        super().__init__(f"Invalid workflow transition {src.value} -> {dst.value}")
        self.src, self.dst = src, dst


def can_transition(src: S, dst: S) -> bool:
    return dst in TRANSITIONS.get(src, set())


def check_transition(src: S, dst: S) -> None:
    if src == dst:
        return
    if not can_transition(src, dst):
        raise InvalidTransition(src, dst)
